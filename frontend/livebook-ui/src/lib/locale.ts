export function detectPreferredLocale(): Locale {
  if (typeof window === "undefined") return "en";
  const stored = window.localStorage.getItem(LOCALE_STORAGE_KEY);
  if (stored === "de" || stored === "en") return stored;
  return window.navigator.language.toLowerCase().startsWith("de") ? "de" : "en";
}

export function localeTag(locale: Locale) {
  return locale === "de" ? "de-DE" : "en-US";
}

export function translate(locale: Locale, key: string) {
  return TRANSLATIONS[locale][key] ?? TRANSLATIONS.en[key] ?? key;
}

export function formatEnumLabel(locale: Locale, value: string) {
  const normalized = value
    .trim()
    .toLowerCase()
    .replace(/[ -]+/g, "_");
  const translated =
    ENUM_TRANSLATIONS[locale][normalized] ??
    ENUM_TRANSLATIONS.en[normalized];
  if (translated) return translated;

  return value
    .replace(/_/g, " ")
    .replace(/\b\w/g, (letter) => letter.toUpperCase());
}

export function formatDateTime(
  locale: Locale,
  value: Date | string | number,
  options?: Intl.DateTimeFormatOptions,
) {
  const date = value instanceof Date ? value : new Date(value);
  if (Number.isNaN(date.getTime())) {
    return typeof value === "string" ? value : "";
  }
  return date.toLocaleString(localeTag(locale), options);
}

export function formatDate(locale: Locale, value: Date | string | number) {
  return formatDateTime(locale, value, {
    dateStyle: "medium",
    timeStyle: "short",
  });
}

export function formatTime(locale: Locale, value: Date | string | number) {
  return formatDateTime(locale, value, {
    hour: "2-digit",
    minute: "2-digit",
  });
}
